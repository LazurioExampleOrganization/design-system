const app = resolve(import.meta.dir, "..");
const SOURCE = join(app, "node_modules/iconoir/icons/regular");
export const TARGET = join(app, "kit/core/icons.ts");

/** The inner markup of an Iconoir icon, checked to have Iconoir's frame. */
function inner(name: string): string {
  const svg = readFileSync(join(SOURCE, `${name}.svg`), "utf8").trim();
  const match = /^<svg\b([^>]*)>([\s\S]*)<\/svg>$/.exec(svg);
  const attributes = Object.fromEntries(
    [...(match?.[1] ?? "").matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]),
  );
  const frame = {
    width: "24",
    height: "24",
    viewBox: "0 0 24 24",
    "stroke-width": "1.5",
    fill: "none",
    xmlns: "http://www.w3.org/2000/svg",
  };
  if (!match || JSON.stringify(attributes, Object.keys(frame)) !== JSON.stringify(frame)) {
    throw new Error(`iconoir ${name}: not a 24 × 24 outline icon`);
  }
  return (match[2] ?? "")
    .split("\n")
    .map((line) => line.trim())
    .join("");
}

export function iconsModule(): string {
  const version = JSON.parse(
    readFileSync(join(app, "node_modules/iconoir/package.json"), "utf8"),
  ).version;
  const entries = ICONS.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(inner(name))},`);
  return [
    `// Generated by app/v1/scripts/icons.ts from Iconoir ${version} (https://iconoir.com, MIT,`,
    "// app/v1/kit/licenses/LICENSE-iconoir.txt). Do not edit: change the list and run `bun run icons`.",
    "// Every icon is an outline on a 24 × 24 grid with a stroke of 1.5 in currentColor.",
    "",
    "export const icons = {",
    ...entries,
    "} as const;",
    "",
    "export type IconName = keyof typeof icons;",
    "",
    "export const ICON_NAMES = Object.keys(icons) as IconName[];",
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(TARGET, iconsModule());
  mkdirLicence();
  console.log(`wrote ${TARGET}`);
}

function mkdirLicence() {
  const licences = join(app, "kit/licenses");
  Bun.spawnSync(["mkdir", "-p", licences]);
  writeFileSync(
    join(licences, "LICENSE-iconoir.txt"),
    readFileSync(join(app, "node_modules/iconoir/LICENSE")),
  );
}
